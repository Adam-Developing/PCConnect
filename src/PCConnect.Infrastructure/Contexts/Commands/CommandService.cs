/// <summary>
/// Opaque cursor over the descending id order. Opaque so the shape can change
/// without breaking a client that stored one.
/// </summary>
public static class Cursor
{
    public static string Encode(long id) =>
        Convert.ToBase64String(System.Text.Encoding.UTF8.GetBytes($"id:{id}"))
            .TrimEnd('=').Replace('+', '-').Replace('/', '_');

    public static long? Decode(string? cursor)
    {
        if (string.IsNullOrWhiteSpace(cursor))
        {
            return null;
        }

        try
        {
            var normalised = cursor.Replace('-', '+').Replace('_', '/');
            normalised += (normalised.Length % 4) switch { 2 => "==", 3 => "=", _ => string.Empty };
            var decoded = System.Text.Encoding.UTF8.GetString(Convert.FromBase64String(normalised));
            return decoded.StartsWith("id:", StringComparison.Ordinal) &&
                   long.TryParse(decoded[3..], CultureInfo.InvariantCulture, out var id)
                ? id
                : throw AppException.Validation("cursor is not valid.", new ErrorDetail("cursor", "format"));
        }
        catch (FormatException)
        {
            throw AppException.Validation("cursor is not valid.", new ErrorDetail("cursor", "format"));
        }
    }
}
